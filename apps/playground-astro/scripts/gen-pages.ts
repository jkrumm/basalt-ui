/**
 * Writes the playground's pages from src/parts/registry.ts (src/pages is generated and gitignored):
 *
 * - /m/<part>/<mode>/     one part in one render mode: what scripts/measure.ts measures
 * - /m/baseline/<mode>/   the smallest React island: the framework runtime alone
 * - /f/<family>/<mode>/   every part of a family in one mode: the cost of several islands on one page
 * - /f/<family>/          every part of a family in every mode, side by side (to look at)
 * - /                     the index: links only, no island
 *
 * A client directive works only on a component imported by name into the .astro file, never through a
 * dynamic tag, so every page imports its demo modules statically; that is why the pages are generated.
 */
import { mkdir, rm, writeFile } from 'node:fs/promises'
import { dirname, join } from 'node:path'
import { FAMILIES, MODES, PARTS } from '../src/parts/registry'
import type { Mode, PartEntry } from '../src/parts/registry'

const ROOT = join(import.meta.dir, '..')
const PAGES = join(ROOT, 'src/pages')
const HEADER = '<!-- @generated by apps/playground-astro/scripts/gen-pages.ts: do not edit -->'

const DIRECTIVE: Record<Mode, string> = {
  static: '',
  visible: ' client:visible',
  idle: ' client:idle',
  load: ' client:load',
  only: ' client:only="react"',
}

type Cell = { part: Pick<PartEntry, 'id' | 'module'>; mode: Mode; alias: string }

/** One measured cell: the probe result on the section, the island (or the failure) inside it. */
function cell({ part, mode, alias }: Cell): string {
  const ssr = `ssr_${alias}`
  const island = `<${alias}${DIRECTIVE[mode]} />`
  if (mode === 'only') {
    return `  <section data-cell data-part="${part.id}" data-mode="only">\n    ${island}\n  </section>`
  }
  return [
    `  <section data-cell data-part="${part.id}" data-mode="${mode}" data-ssr={state(${ssr})} data-ssr-error={detail(${ssr})}>`,
    `    {${ssr}.ok ? ${island} : <div data-ssr-failed>{${ssr}.error}</div>}`,
    '  </section>',
  ].join('\n')
}

function page({
  depth,
  title,
  cells,
}: {
  depth: number
  title: string
  cells: readonly Cell[]
}): string {
  const up = '../'.repeat(depth)
  const imports = new Map<string, string>()
  for (const c of cells) imports.set(c.alias, c.part.module)
  const probes = cells.filter((c) => c.mode !== 'only')
  const lines = [
    '---',
    HEADER.replace('<!--', '//').replace(' -->', ''),
    `import Part from '${up}layouts/Part.astro'`,
    ...(probes.length ? [`import { detail, probe, state } from '${up}lib/probe'`] : []),
    ...[...imports].map(
      ([alias, module]) => `import { Demo as ${alias} } from '${up}parts/${module}'`,
    ),
    ...[...new Set(probes.map((c) => c.alias))].map((a) => `const ssr_${a} = await probe(${a})`),
    '---',
    '',
    `<Part title="${title}">`,
    ...cells.map(cell),
    '</Part>',
    '',
  ]
  return lines.join('\n')
}

const alias = (id: string): string =>
  'P' + id.replace(/(^|-)(\w)/g, (_, __, ch: string) => ch.toUpperCase())

const files = new Map<string, string>()
const BASELINE = { id: 'baseline', module: 'baseline' }

for (const mode of MODES) {
  for (const part of [...PARTS, BASELINE]) {
    files.set(
      `m/${part.id}/${mode}.astro`,
      page({
        depth: 3,
        title: `${part.id} · ${mode}`,
        cells: [{ part, mode, alias: alias(part.id) }],
      }),
    )
  }
  for (const family of FAMILIES) {
    const parts = PARTS.filter((p) => p.family === family)
    if (!parts.length) continue
    files.set(
      `f/${family}/${mode}.astro`,
      page({
        depth: 3,
        title: `${family} · ${mode}`,
        cells: parts.map((part) => ({ part, mode, alias: alias(part.id) })),
      }),
    )
  }
}
for (const family of FAMILIES) {
  const parts = PARTS.filter((p) => p.family === family)
  if (!parts.length) continue
  files.set(
    `f/${family}/index.astro`,
    page({
      depth: 3,
      title: family,
      cells: parts.flatMap((part) => MODES.map((mode) => ({ part, mode, alias: alias(part.id) }))),
    }),
  )
}

const links = FAMILIES.filter((f) => PARTS.some((p) => p.family === f))
  .map((f) => `    <li><a href="/f/${f}/">${f}</a></li>`)
  .join('\n')
files.set(
  'index.astro',
  [
    '---',
    HEADER.replace('<!--', '//').replace(' -->', ''),
    "import Part from '../layouts/Part.astro'",
    '---',
    '',
    '<Part title="basalt-ui in Astro">',
    '  <ul>',
    links,
    '  </ul>',
    '</Part>',
    '',
  ].join('\n'),
)

await rm(PAGES, { recursive: true, force: true })
for (const [path, text] of files) {
  const target = join(PAGES, path)
  await mkdir(dirname(target), { recursive: true })
  await writeFile(target, text)
}
console.log(`gen-pages: ${files.size} pages for ${PARTS.length} parts`)
