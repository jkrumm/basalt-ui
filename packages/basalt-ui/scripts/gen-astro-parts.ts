/**
 * Writes `src/astro/parts.ts`, the part table `basalt-ui/astro` ships, from the Astro matrix record
 * (`docs/v3/verdicts/astro-matrix.json`): each part's id, family, the exports it covers, how it
 * behaves without JavaScript and its best render mode. `basaltAstro()` fails a build on a `required`
 * part outside an island and `doctor` reads which parts a `site` root may import, both from it.
 *
 * `src/astro/astro.test.tsx` holds the table to the record, so a matrix change that moves a part fails
 * until this runs again.
 *
 * Usage: bun packages/basalt-ui/scripts/gen-astro-parts.ts
 */
import { spawnSync } from 'node:child_process'
import { readFileSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'

const PKG_ROOT = join(import.meta.dir, '..')
export const MATRIX = join(PKG_ROOT, '../../docs/v3/verdicts/astro-matrix.json')
export const OUT = join(PKG_ROOT, 'src/astro/parts.ts')

type MatrixPart = {
  id: string
  family: string
  covers: string[]
  interaction: string
  best: string
}

/** The source of `src/astro/parts.ts` for the matrix record `json`. */
export function partsSource(json: string): string {
  const parts = (JSON.parse(json) as { parts: MatrixPart[] }).parts
  const quote = (s: string): string => `'${s}'`
  const union = (values: Iterable<string>): string =>
    [...new Set(values)].toSorted().map(quote).join(' | ')
  const rows = parts.map(
    (p) =>
      `  { id: ${quote(p.id)}, family: ${quote(p.family)}, covers: [${p.covers.map(quote).join(', ')}], interaction: ${quote(p.interaction)}, best: ${quote(p.best)} },`,
  )
  return [
    '// @generated by scripts/gen-astro-parts.ts from docs/v3/verdicts/astro-matrix.json; do not edit.',
    '',
    '/**',
    ' * One part as an Astro page sees it: `interaction` is what it does with no JavaScript (`none`: the',
    ' * HTML is the whole part; `enhance`: it works static and gains behaviour in an island; `required`:',
    ' * it is dead without one) and `best` the render mode the matrix measured as its best.',
    ' */',
    'export type AstroPart = {',
    '  /** The part id, also the `data-slot` its root or trigger renders (or its prefix). */',
    '  id: string',
    `  family: ${union(parts.map((p) => p.family))}`,
    '  /** The exports the part covers. */',
    '  covers: readonly string[]',
    `  interaction: ${union(parts.map((p) => p.interaction))}`,
    `  best: ${union(parts.map((p) => p.best))}`,
    '}',
    '',
    '/**',
    ' * Every part the Astro matrix measures, in its order: how each behaves with no JavaScript and the',
    ` * render mode it measured best in. \`basaltAstro()\` fails a build on a \`required\` part outside an island.`,
    ' *',
    ' * @useWhen deciding whether a part on an Astro page needs a client directive, and which one',
    ' * @neverWhen the page is an app page (a Vite or TanStack Start app hydrates the whole tree)',
    ' */',
    'export const ASTRO_PARTS: readonly AstroPart[] = [',
    ...rows,
    ']',
    '',
  ].join('\n')
}

if (import.meta.main) {
  writeFileSync(OUT, partsSource(readFileSync(MATRIX, 'utf8')))
  spawnSync('bunx', ['oxfmt', OUT], { stdio: 'inherit' })
}
