#!/usr/bin/env bun
/**
 * Emit `src/tokens/basalt-names.ts` — every `--basalt-*` name basalt emits, the baseline `release-migrating`
 * diffs against the previous tag so a removed name needs a migration row.
 *
 * It is a checked-in literal because a tag has to carry it. It is derived, never hand-edited, from:
 *
 * 1. `buildPaletteCss()` with no options — the exact function `basalt-ui tokens:css`
 *    writes the stylesheet from, so the palette half IS its name set.
 * 2. The v3 token table (`TOKENS`) — every `--basalt-<name>` the v3 sheets emit (`--basalt-text-xs-lh`,
 *    `--basalt-canvas`, …), so a consumer's `var(--basalt-text-xs-lh)` is never judged unknown.
 * 3. The component-scoped names basalt's own source declares (`--basalt-hit-gap`,
 *    `--basalt-space-icon-size`), from every non-test file:
 *    a declaration (`--basalt-x:` — in a `.css` file or in CSS text inside a `.ts`/`.tsx` template
 *    literal) and, in `.ts`/`.tsx`, ANY quoted `'--basalt-x'` string literal. The quoted form is
 *    deliberately broad — a style-object key, a `setProperty` name, a const — so a quoted
 *    `--basalt-*` anywhere in shipped source enters the allowlist. That errs toward NOT reporting; it
 *    can never leave a name basalt emits out of the baseline.
 *
 * It also emits `src/common/basalt-families.ts`: the families of that FULL name set (`basaltFamilies`),
 * component-scoped ones included (`keyboard`), in their own file so `src/tokens` can import them
 * without the name list.
 *
 * `scripts/gen-basalt-names.test.ts` re-derives the set and fails on any drift, pointing back here.
 */
import { readFileSync, writeFileSync } from 'node:fs'
import { resolve } from 'node:path'
import { Glob } from 'bun'
import { basaltFamilies } from '../src/common/basalt-family.ts'
import { buildPaletteCss } from '../src/tokens/index.ts'
import { TOKENS } from '../src/tokens/table.ts'

const ROOT = resolve(import.meta.dirname, '..')
export const BASALT_NAMES_PATH = resolve(ROOT, 'src/tokens/basalt-names.ts')
export const BASALT_FAMILIES_PATH = resolve(ROOT, 'src/common/basalt-families.ts')

const DECLARATION = /(--basalt-[A-Za-z0-9-]*[A-Za-z0-9])\s*:/g
// A name a stylesheet reads with a fallback, `var(--basalt-x, 1rem)`, is an optional override hook a
// host sets (`IconSlot`'s `--basalt-space-icon-size`): it is basalt's even when no source declares it.
const OVERRIDE_HOOK = /var\(\s*(--basalt-[A-Za-z0-9-]*[A-Za-z0-9])\s*,/g
const QUOTED = /['"](--basalt-[A-Za-z0-9-]*[A-Za-z0-9])['"]/g

/** The generator's own outputs: scanning one would keep a name the sources no longer emit alive forever. */
export const GENERATED_OUTPUTS: ReadonlySet<string> = new Set(['src/tokens/basalt-names.ts'])

export function collectBasaltNames(): string[] {
  const names = new Set<string>()
  const add = (text: string, re: RegExp) => {
    for (const [, name] of text.matchAll(re)) names.add(name as string) // group 1 is not optional
  }
  add(buildPaletteCss(), DECLARATION)
  for (const { name } of TOKENS) names.add(`--basalt-${name}`)
  for (const rel of new Glob('src/**/*.{ts,tsx,css}').scanSync(ROOT)) {
    // `src/css/` is the v3 sheet set: its names are judged by the v3 `check-tokens`, never fed to
    // this 2.x allowlist; `src/tokens/golden/` is the same v3 output pinned byte for byte.
    if (
      GENERATED_OUTPUTS.has(rel) ||
      rel.startsWith('src/css/') ||
      rel.startsWith('src/tokens/golden/') ||
      /\.test\.tsx?$/.test(rel)
    ) {
      continue
    }
    const text = readFileSync(resolve(ROOT, rel), 'utf8')
    add(text, DECLARATION)
    if (rel.endsWith('.css')) add(text, OVERRIDE_HOOK)
    else add(text, QUOTED)
  }
  return [...names].toSorted()
}

export function renderBasaltNames(names: readonly string[]): string {
  return [
    '// GENERATED by scripts/gen-basalt-names.ts — do not edit. `gen-basalt-names.test.ts` fails on drift.',
    '',
    '/** Every `--basalt-*` name basalt emits: `buildPaletteCss()`, the v3 token table and the component-scoped names. */',
    'export const BASALT_NAMES: readonly string[] = [',
    ...names.map((n) => `  '${n}',`),
    ']',
    '',
  ].join('\n')
}

export function renderBasaltFamilies(names: readonly string[]): string {
  return [
    '// GENERATED by scripts/gen-basalt-names.ts — do not edit. `gen-basalt-names.test.ts` fails on drift.',
    '',
    '/**',
    ' * The families every emitted `--basalt-*` name lives in (`basaltFamilies`) — basalt-owned:',
    ' * `groupTokens`/`seriesTokens` throw on a consumer ref there.',
    ' */',
    'export const BASALT_FAMILIES: readonly string[] = [',
    ...basaltFamilies(names).map((f) => `  '${f}',`),
    ']',
    '',
  ].join('\n')
}

if (import.meta.main) {
  const names = collectBasaltNames()
  writeFileSync(BASALT_NAMES_PATH, renderBasaltNames(names))
  writeFileSync(BASALT_FAMILIES_PATH, renderBasaltFamilies(names))
  console.log(
    `gen-basalt-names: ${names.length} names → src/tokens/basalt-names.ts, families → src/common/basalt-families.ts`,
  )
}
