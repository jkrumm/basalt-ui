#!/usr/bin/env bun
/**
 * Write the charts layer's `:root` block (`chartEngineCss()`, `docs/V2-SPEC.md` § 9.5) into
 * `src/styles.css` between its two markers. The block lives in the SOURCE stylesheet, not only in
 * `dist/`, because a Vite alias to `src/` (the playground) and the layout fixture serve the source
 * file; `copy-assets.mjs` then ships it unchanged as `dist/styles.css`.
 *
 * `--check` exits 1 on drift instead of writing; `src/charts/engine.test.tsx` asserts the same.
 */
import { readFileSync, writeFileSync } from 'node:fs'
import { resolve } from 'node:path'
import { chartEngineCss } from '../src/charts/theme.ts'

const FILE = resolve(import.meta.dirname, '..', 'src', 'styles.css')
const START =
  '/* chart-engine:start — generated by scripts/gen-chart-css.ts from chartEngineCss() */'
const END = '/* chart-engine:end */'

// The block IS `chartEngineCss()`, laid out the way the formatter keeps `styles.css`.
const engine = chartEngineCss()
const decls = engine
  .slice(engine.indexOf('{') + 1, engine.lastIndexOf('}'))
  .split(';')
  .map((decl) => `    ${decl.replace(':', ': ')};`)
  .join('\n')
const block = `${START}\n@layer basalt {\n  :root {\n${decls}\n  }\n}\n${END}`

const css = readFileSync(FILE, 'utf8')
const from = css.indexOf(START)
const to = css.indexOf(END)
const next =
  from === -1 || to === -1 || to < from
    ? `${css.trimEnd()}\n\n${block}\n`
    : `${css.slice(0, from)}${block}${css.slice(to + END.length)}`

if (process.argv.includes('--check')) {
  if (next !== css) {
    console.error(
      'gen-chart-css: src/styles.css is out of date — run `bun scripts/gen-chart-css.ts`',
    )
    process.exit(1)
  }
  console.log('gen-chart-css: in sync')
} else {
  writeFileSync(FILE, next)
  console.log('gen-chart-css: src/styles.css updated')
}
