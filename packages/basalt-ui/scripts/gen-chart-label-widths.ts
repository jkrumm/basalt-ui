#!/usr/bin/env bun
/**
 * Write `src/charts/chart-labels-widths.gen.ts`: the advance width of every glyph the chart labels
 * use, in the DEFAULT chart sans (Nunito Sans Variable, `@fontsource-variable/nunito-sans`), with
 * tabular figures on (the chart host sets `font-variant-numeric: tabular-nums`), at weights
 * 400/500/600/700. The real woff2 is loaded in headless Chrome and each glyph is measured once at
 * `REFERENCE_SIZE`; the table stores em fractions. `chartLabels.width` reads the table, so it never
 * measures at runtime and a server render equals a client render. Kerning is off: each glyph is
 * measured alone and the runtime sums advances.
 *
 * Needs Chrome (`channel: 'chrome'`, as `apps/playground/scripts/shots.ts`). Run from
 * `packages/basalt-ui`: `bun scripts/gen-chart-label-widths.ts`.
 */
import { readFileSync, writeFileSync } from 'node:fs'
import { createRequire } from 'node:module'
import { dirname, join } from 'node:path'
import { chromium } from 'playwright-core'

const REFERENCE_SIZE = 100
const WEIGHTS = [400, 500, 600, 700] as const
const OUT = new URL('../src/charts/chart-labels-widths.gen.ts', import.meta.url)

/**
 * Printable ASCII, Latin-1 (U+00A0-00FF) and the typographic punctuation a label uses. Every glyph
 * lies in the latin subset's `unicode-range`, so none is measured in a fallback face.
 */
function glyphs(): string {
  const out: string[] = []
  for (let c = 0x20; c <= 0x7e; c++) out.push(String.fromCodePoint(c))
  for (let c = 0xa1; c <= 0xff; c++) if (c !== 0xad) out.push(String.fromCodePoint(c))
  out.push(...' ‐‑–—―‘’‚“”„•…‰′″‹›€™−↑↓')
  return [...new Set(out)].join('')
}

const require = createRequire(import.meta.url)
const pkgJson = require.resolve('@fontsource-variable/nunito-sans/package.json')
const pkgDir = dirname(pkgJson)
const version = (JSON.parse(readFileSync(pkgJson, 'utf8')) as { version: string }).version
const fontFile = 'files/nunito-sans-latin-wght-normal.woff2'
const fontB64 = readFileSync(join(pkgDir, fontFile)).toString('base64')

const browser = await chromium.launch({ channel: 'chrome' })
const chromeVersion = browser.version()
const page = await browser.newPage()
await page.setContent(
  `<style>
@font-face { font-family: 'Probe'; font-weight: 200 1000; src: url(data:font/woff2;base64,${fontB64}) format('woff2-variations'); }
span { font-family: 'Probe', serif; font-size: ${REFERENCE_SIZE}px; font-variant-numeric: tabular-nums; font-kerning: none; white-space: pre; position: absolute; }
</style>`,
)

const chars = glyphs()
const measured = await page.evaluate(
  async ({ chars, weights, size }) => {
    const out: Record<number, number[]> = {}
    for (const weight of weights) {
      await document.fonts.load(`${weight} ${size}px Probe`, 'a0')
      const span = document.createElement('span')
      span.style.fontWeight = String(weight)
      document.body.append(span)
      out[weight] = [...chars].map((ch) => {
        span.textContent = ch
        return span.getBoundingClientRect().width / size
      })
      span.remove()
    }
    return out
  },
  { chars, weights: [...WEIGHTS], size: REFERENCE_SIZE },
)
await browser.close()

const round = (n: number) => Math.round(n * 10000) / 10000
const rows = WEIGHTS.map((weight) => {
  const advances = (measured[weight] ?? []).map(round)
  const mean = round(advances.reduce((a, b) => a + b, 0) / advances.length)
  return `  ${weight}: { mean: ${mean}, advances: [${advances.join(', ')}] },`
})

const source = `// @generated by scripts/gen-chart-label-widths.ts: do not edit. Regenerate with
// \`bun scripts/gen-chart-label-widths.ts\` from packages/basalt-ui (needs Chrome).
// Face: @fontsource-variable/nunito-sans ${version}, ${fontFile}, tabular figures on, no kerning.
// Measured in Chrome ${chromeVersion} at ${REFERENCE_SIZE}px; values are em fractions.

/** The glyphs the table knows, in \`advances\` order. */
export const GLYPHS = ${JSON.stringify(chars)}

/** Advance per glyph and the mean over the table (the width of a glyph the table lacks), per weight. */
export const WIDTHS = {
${rows.join('\n')}
} as const satisfies Record<number, { mean: number; advances: readonly number[] }>
`
writeFileSync(OUT, source)
const fmt = Bun.spawnSync(['bunx', 'oxfmt', OUT.pathname], { stdout: 'inherit', stderr: 'inherit' })
if (fmt.exitCode !== 0) process.exit(fmt.exitCode ?? 1)
console.log(
  `gen-chart-label-widths: ${chars.length} glyphs x ${WEIGHTS.length} weights, Chrome ${chromeVersion}`,
)
