#!/usr/bin/env bun
/**
 * Write the dense control tier's rule (`denseCtlCss()`) into `src/styles.css` between its two
 * markers, so the overrides come from the same `CTL_HEIGHT_VARS` list `ctlSizeVars` reads. Same
 * shape as `gen-chart-css.ts`; `--check` exits 1 on drift.
 */
import { readFileSync, writeFileSync } from 'node:fs'
import { resolve } from 'node:path'
import { denseCtlCss } from '../src/theme/ctl-vars.ts'

const FILE = resolve(import.meta.dirname, '..', 'src', 'styles.css')
const START = '  /* dense-ctl:start — generated by scripts/gen-dense-css.ts from CTL_HEIGHT_VARS */'
const END = '  /* dense-ctl:end */'

const block = `${START}\n${denseCtlCss()}\n${END}`
const css = readFileSync(FILE, 'utf8')
const from = css.indexOf(START)
const to = css.indexOf(END)
if (from === -1 || to === -1 || to < from) {
  console.error('gen-dense-css: markers missing in src/styles.css')
  process.exit(1)
}
const next = `${css.slice(0, from)}${block}${css.slice(to + END.length)}`

if (process.argv.includes('--check')) {
  if (next !== css) {
    console.error(
      'gen-dense-css: src/styles.css is out of date — run `bun scripts/gen-dense-css.ts`',
    )
    process.exit(1)
  }
  console.log('gen-dense-css: in sync')
} else {
  writeFileSync(FILE, next)
  console.log('gen-dense-css: src/styles.css updated')
}
