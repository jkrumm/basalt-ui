const PART_NAME = /^[A-Z][A-Za-z0-9]*$/

export type Part = { name: string; subpath: string; useWhen: string; file: string }
export type Block = { name: string; summary: string }

function unquote(value: string): string {
  if (value.length >= 2 && value.startsWith("'") && value.endsWith("'")) {
    return value.slice(1, -1).replaceAll("''", "'")
  }
  return value
}

/** The `key: value` lines of a leading `---` block; empty when the doc has no frontmatter. */
export function parseFrontmatter(text: string): Map<string, string> {
  const front = new Map<string, string>()
  const lines = text.split('\n')
  if (lines[0] !== '---') return front
  const close = lines.indexOf('---', 1)
  if (close === -1) return front
  for (const line of lines.slice(1, close)) {
    const m = /^([a-z][a-z -]*?)\s*:\s*(.*)$/.exec(line)
    if (m) front.set(m[1]!, unquote(m[2]!.trim()))
  }
  return front
}

const collapse = (text: string): string => text.replace(/\s+/g, ' ').trim()
const byName = (a: { name: string }, b: { name: string }): number =>
  a.name < b.name ? -1 : a.name > b.name ? 1 : 0

/** Every part in `docsDir`, sorted by name. Throws on an unmapped subpath or a missing field. */
export function readParts(docsDir: string): Part[] {
  const parts: Part[] = []
  for (const file of readdirSync(docsDir)
    .filter((f) => f.endsWith('.md'))
    .toSorted()) {
    const front = parseFrontmatter(readFileSync(join(docsDir, file), 'utf8'))
    const name = front.get('name')
    if (name === undefined || !PART_NAME.test(name)) continue
    const subpath = front.get('subpath')
    if (subpath === undefined) throw new Error(`docs/${file}: part ${name} has no subpath:`)
    if (SKIPPED_SUBPATHS.has(subpath)) continue
    if (SUBPATH_QUESTIONS[subpath] === undefined) {
      throw new Error(
        `docs/${file}: subpath ${subpath} has no question in SUBPATH_QUESTIONS (scripts/gen-parts.ts)`,
      )
    }
    const useWhen = front.get('use when')
    if (useWhen === undefined) throw new Error(`docs/${file}: part ${name} has no use when:`)
    parts.push({ name, subpath, useWhen: collapse(useWhen).replace(/\.$/, ''), file })
  }
  const names = parts.map((p) => p.name)
  const dup = names.find((n, i) => names.indexOf(n) !== i)
  if (dup !== undefined) throw new Error(`two docs declare part name ${dup}`)
  return parts.toSorted(byName)
}

/** Every block in `blocksDir` (one directory each, with a block.json), sorted by name. */
export function readBlocks(blocksDir: string): Block[] {
  return readdirSync(blocksDir, { withFileTypes: true })
    .filter((d) => d.isDirectory())
    .map((d) => {
      const raw: Partial<Record<'name' | 'summary', unknown>> = JSON.parse(
        readFileSync(join(blocksDir, d.name, 'block.json'), 'utf8'),
      )
      if (typeof raw.name !== 'string' || typeof raw.summary !== 'string') {
        throw new Error(`blocks/${d.name}/block.json needs a name and a summary`)
      }
      return { name: raw.name, summary: collapse(raw.summary) }
    })
    .toSorted(byName)
}

/** The PascalCase value exports a primitive module names, its sub-parts (`DialogContent` under `Dialog`) left out. */
export function primitiveNames(names: readonly string[]): string[] {
  const parts = names.filter((n) => PART_NAME.test(n) && n !== n.toUpperCase())
  return parts.filter((n) => !parts.some((other) => other !== n && n.startsWith(other)))
}

/** A primitive's doc names its module, not one export: list the module by its path and its parts. */
function partLine(p: Part, exportsOf: (subpath: string) => readonly string[]): string {
  if (!p.subpath.startsWith('basalt-ui/ui/'))
    return `- \`${p.name}\` (\`${p.subpath}\`): ${p.useWhen}`
  const names = primitiveNames(exportsOf(p.subpath))
  if (names.length === 0) return `- \`${p.subpath}\`: ${p.useWhen}`
  return `- \`${p.subpath}\` (${names.map((n) => `\`${n}\``).join(', ')}): ${p.useWhen}`
}

export function renderParts(
  parts: readonly Part[],
  blocks: readonly Block[],
  exportsOf: (subpath: string) => readonly string[] = () => [],
): string {
  const lines = [HEADER, '', '# Parts', '', INTRO, '', `## ${BLOCK_HEADING}`, '']
  for (const block of blocks) lines.push(`- \`basalt-ui add ${block.name}\`: ${block.summary}`)
  lines.push('')
  const headings = [...new Set(Object.values(SUBPATH_QUESTIONS))]
  for (const heading of headings) {
    const group = parts.filter((p) => SUBPATH_QUESTIONS[p.subpath] === heading)
    if (group.length === 0) continue
    lines.push(`## ${heading}`, '')
    for (const p of group) lines.push(partLine(p, exportsOf))
    lines.push('')
  }
  return lines.join('\n')
}

/** parts.md from the shipped docs, blocks and export-surface shards. */
export function generateParts(): string {
  const shards: Record<string, readonly string[]> = readShards(join(PKG, 'scripts/export-surface'))
  const exportsOf = (subpath: string): readonly string[] =>
    shards[`./${subpath.slice('basalt-ui/'.length)}`] ?? []
  return renderParts(readParts(DOCS_DIR), readBlocks(BLOCKS_DIR), exportsOf)
}

function main(): void {
  const text = generateParts()
  if (process.argv.includes('--check')) {
    const committed = existsSync(PARTS_FILE) ? readFileSync(PARTS_FILE, 'utf8') : ''
    if (committed === text) return
    console.error(
      `${relative(PKG, PARTS_FILE)} is stale: run bun packages/basalt-ui/scripts/gen-parts.ts`,
    )
    process.exit(1)
  }
  writeFileSync(PARTS_FILE, text)
  console.log(`wrote ${relative(PKG, PARTS_FILE)}`)
}

if (import.meta.path === Bun.main) {
  main()
}
