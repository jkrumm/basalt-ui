import { useId } from 'react'

/**
 * Names a control that has no VISIBLE Mantine `label`, and does it differently per surface — which
 * is the whole reason this is one helper instead of an `aria-label` sprinkled per call site.
 *
 * In the SHEET and the PANEL the visible `PanelRow` heading is right there, so the control points
 * at it (`aria-labelledby`) and the heading stops being decoration. In the PILL surface there is no
 * visible name to point at — the pill text is the VALUE (`EUR`, `30d`, `3 channels`) — so the
 * control carries the filter's own name instead. Either way the announced name is what is being
 * filtered, not what it currently holds.
 *
 * The id is generated by the CONTROL, not by `PanelRow`, because the control renders its own
 * `PanelRow`: an id published downward through context could never reach the sibling that needs it.
 *
 * @example
 * const { labelId, nameProps } = useControlName(label, inSheet || inPanel)
 * <Radio.Group {...nameProps} …/>
 * // and, in the sheet/panel branch: <PanelRow label={label} labelId={labelId}>…</PanelRow>
 */
export function useControlName(
  label: string,
  named: boolean,
): {
  labelId: string
  nameProps: { 'aria-labelledby': string } | { 'aria-label': string }
} {
  const labelId = useId()
  return {
    labelId,
    nameProps: named ? { 'aria-labelledby': labelId } : { 'aria-label': label },
  }
}
