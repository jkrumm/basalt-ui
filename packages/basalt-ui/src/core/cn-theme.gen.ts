import { readFileSync, writeFileSync } from 'node:fs'
import { bridgeEntries } from '../tokens/table'

const OUT = new URL('./cn-theme.ts', import.meta.url)
const HEADER = '// @generated by core/cn-theme.gen.ts from tokens/table.ts: do not edit'

/** Theme names per Tailwind namespace, read from the bridge targets (table order). */
function names(namespace: string, skip?: RegExp): string[] {
  const prefix = `--${namespace}-`
  const out: string[] = []
  for (const { tw } of bridgeEntries()) {
    if (!tw.startsWith(prefix)) continue
    const name = tw.slice(prefix.length)
    if (name.includes('--') || skip?.test(name) || out.includes(name)) continue
    out.push(name)
  }
  return out
}

export function themeNames() {
  return {
    textSizes: names('text'),
    colors: names('color'),
    radii: names('radius'),
    shadows: names('shadow'),
    fonts: names('font', /^weight-/),
    fontWeights: names('font-weight'),
    durations: names('duration'),
    eases: names('ease'),
  }
}

/** The committed `cn-theme.ts`, formatted the way oxfmt leaves it. */
export function generate(): string {
  const lines = Object.entries(themeNames()).map(([key, list]) => {
    const items = list.map((n) => `'${n}'`)
    const inline = `  ${key}: [${items.join(', ')}],`
    if (inline.length <= 100) return inline
    return `  ${key}: [\n${items.map((i) => `    ${i},`).join('\n')}\n  ],`
  })
  return `${HEADER}\nexport const CN_THEME = {\n${lines.join('\n')}\n} as const\n`
}

if (import.meta.main) {
  const next = generate()
  if (process.argv.includes('--check')) {
    if (readFileSync(OUT, 'utf8') !== next) {
      // oxlint-disable-next-line no-console
      console.error('cn-theme.ts is stale: run `bun packages/basalt-ui/src/core/cn-theme.gen.ts`')
      process.exit(1)
    }
  } else {
    writeFileSync(OUT, next)
  }
}
