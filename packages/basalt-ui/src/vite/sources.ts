/**
 * `<app>/.basalt/sources.css`: the Tailwind `@source` lines for the basalt-ui files this app
 * reaches. `@source` is directory-granular, so the list is positive per reached subpath directory
 * and `@source not` per primitive the app does not reach, plus the npm copy of every ejected one
 * (its local file is the app's own source). Written each run, only when the bytes change.
 */
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'

import type { Closure } from './graph'
import { packageDir, relativePosix } from './graph'

export const SOURCES_PATH = '.basalt/sources.css'

/** The src directory a runtime subpath lives in: `.` is `core`. */
const dirOf = (subpath: string): string => (subpath === '.' ? 'core' : subpath)

export type SourcesInput = {
  /** The Vite root; the file lands at `<appRoot>/.basalt/sources.css`. */
  appRoot: string
  pkgRoot: string
  closure: Closure
  /** Every primitive the installed package ships. */
  shipped: readonly string[]
  /** Primitives this app ejected. */
  ejected: readonly string[]
}

export function renderSources(input: SourcesInput): string {
  const { appRoot, pkgRoot, closure, shipped, ejected } = input
  const from = join(appRoot, '.basalt')
  const at = (dir: string): string => relativePosix(from, packageDir(pkgRoot, dir))
  const reached = new Set(closure.primitives)
  const local = new Set(ejected)

  const positive = closure.subpaths
    .map(dirOf)
    .filter((dir) => existsSync(packageDir(pkgRoot, dir)))
    .toSorted()
  const excluded = shipped.filter((name) => !reached.has(name) || local.has(name))

  return [
    '/* @generated by basalt() from basalt-ui/vite on every build and dev start; do not edit, do not commit. */',
    ...positive.map((dir) => `@source "${at(dir)}";`),
    ...excluded.map((name) => `@source not "${at('ui')}/${name}.*";`),
    '',
  ].join('\n')
}

/** Writes the file when its bytes differ; returns whether it wrote. */
export function writeSources(appRoot: string, css: string): boolean {
  const path = join(appRoot, SOURCES_PATH)
  if (existsSync(path) && readFileSync(path, 'utf8') === css) return false
  mkdirSync(dirname(path), { recursive: true })
  writeFileSync(path, css)
  return true
}
